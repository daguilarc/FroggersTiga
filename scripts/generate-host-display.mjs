#!/usr/bin/env node
/** Generate web/src/hostDisplay.generated.ts from sim/ParamDisplayNames.hpp and sim/HostPanelLayout.hpp */
import { readFileSync, writeFileSync } from "node:fs";
import { dirname, join } from "node:path";
import { fileURLToPath } from "node:url";

const root = join(dirname(fileURLToPath(import.meta.url)), "..");
const outPath = join(root, "web/src/hostDisplay.generated.ts");
const checkOnly = process.argv.includes("--check");

function pagesFromHpp(text) {
  const block = text.match(/kPages\[kNumHostPages\] = \{(.*?)\};/s);
  if (!block) throw new Error("could not parse kPages from ParamDisplayNames.hpp");
  return [...block[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
}

function tableFromHpp(text) {
  const block = text.match(/kTable\[kNumHostPages\]\[kNumRows\] = \{(.*?)\};/s);
  if (!block) throw new Error("could not parse kTable from ParamDisplayNames.hpp");
  return block[1]
    .split("\n")
    .map((line) => line.trim().replace(/,$/, ""))
    .filter((line) => line.startsWith("{"))
    .map((line) => [...line.matchAll(/"([^"]+)"/g)].map((m) => m[1]));
}

function pairFromHpp(text) {
  const block = text.match(/kLabels\[4\] = \{(.*?)\};/s);
  if (!block) throw new Error("could not parse pair-AR labels from ParamDisplayNames.hpp");
  return [...block[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]);
}

function globalStripFromHpp(text) {
  const labels = [];
  const re = /case GlobalStripAction::\w+:\s*return "([^"]+)"/g;
  let match;
  while ((match = re.exec(text)) !== null) {
    labels.push(match[1]);
  }
  if (labels.length !== 4) {
    throw new Error(`expected 4 global-strip labels, got ${labels.length}`);
  }
  return labels;
}

function modCatalogFromHpp(text) {
  const block = text.match(/kModRackCatalog\[\] = \{(.*?)\};/s);
  if (!block) throw new Error("could not parse kModRackCatalog from HostPanelLayout.hpp");
  const rows = [];
  const rowRe = /\{(\d+),\s*ModCellPresentation::(\w+),\s*(true|false),\s*(true|false),\s*(true|false),\s*(true|false)\}/g;
  let match;
  while ((match = rowRe.exec(block[1])) !== null) {
    rows.push({
      modIndex: Number(match[1]),
      presentation: match[2] === "Scope" ? "scope" : "led",
      includeDesktop: match[3] === "true",
      includeWeb: match[4] === "true",
      includeVst: match[5] === "true",
      includeVcv: match[6] === "true",
    });
  }
  if (rows.length !== 5) {
    throw new Error(`expected 5 mod-rack catalog rows, got ${rows.length}`);
  }
  return rows;
}

function scopeCapacityFromHpp(text) {
  const match = text.match(/kScopeSampleCapacity = (\d+)/);
  if (!match) throw new Error("could not parse kScopeSampleCapacity from HostPanelLayout.hpp");
  return Number(match[1]);
}

function modLedFullBrightnessFromHpp(text) {
  const match = text.match(/kModLedFullBrightnessCv\s*=\s*([\d.]+)f/);
  if (!match) throw new Error("could not parse kModLedFullBrightnessCv from ModLedBrightness.hpp");
  return Number(match[1]);
}

function v2ExpandedRowCountFromHpp(text) {
  const match = text.match(/kV2ExpandedNumRows\s*=\s*(\d+)/);
  if (!match) throw new Error("could not parse kV2ExpandedNumRows from V2ParamDisplayNames.hpp");
  return Number(match[1]);
}

function v2ExpansionTailFromHpp(text) {
  const block = text.match(/kExpansionTail\[5\]\[3\] = \{(.*?)\};/s);
  if (!block) throw new Error("could not parse kExpansionTail from V2ParamDisplayNames.hpp");
  const rows = [];
  const rowRe = /\{([^}]+)\}/g;
  let match;
  while ((match = rowRe.exec(block[1])) !== null) {
    rows.push([...match[1].matchAll(/"([^"]+)"/g)].map((m) => m[1]));
  }
  if (rows.length !== 5) {
    throw new Error(`expected 5 v2 expansion rows, got ${rows.length}`);
  }
  for (const row of rows) {
    if (row.length !== 3) {
      throw new Error(`expected 3 v2 expansion labels per page, got ${row.length}`);
    }
  }
  return rows;
}

function buildV2WebTable(v1Table, expansions) {
  return v1Table.map((pageRows, pageIndex) => {
    if (pageIndex === 0) {
      return pageRows;
    }
    return [...pageRows.slice(0, 7), ...expansions[pageIndex - 1]];
  });
}

function projectModBay(catalog, hostKey) {
  return catalog
    .filter((row) => row[hostKey])
    .map(({ modIndex, presentation }) => ({ modIndex, kind: presentation }));
}

function emitTs({
  pages,
  table,
  pairLabels,
  globalStrip,
  scopeSize,
  modLedFullBrightnessCv,
  expandedCoreKnobCount,
  desktopModBay,
  webModBay,
  vstModBay,
  vcvModBay,
}) {
  return `// Generated by scripts/generate-host-display.mjs — do not edit.
export const HOST_PAGE_COUNT = ${pages.length} as const;
export const CORE_KNOB_COUNT = ${table[0]?.length ?? 8} as const;
export const EXPANDED_CORE_KNOB_COUNT = ${expandedCoreKnobCount} as const;
export const PAIR_AR_KNOB_COUNT = ${pairLabels.length} as const;
export const TOTAL_KNOB_COUNT = EXPANDED_CORE_KNOB_COUNT + PAIR_AR_KNOB_COUNT;
export const HOST_PAGE_NAMES = ${JSON.stringify(pages)} as const;
export const HOST_PAGE_KNOB_LABELS: readonly (readonly string[])[] = ${JSON.stringify(table)};
export const PAIR_AR_KNOB_LABELS = ${JSON.stringify(pairLabels)} as const;
export const GLOBAL_STRIP_LABELS = ${JSON.stringify(globalStrip)} as const;
export const SCOPE_SIZE = ${scopeSize} as const;
export const MOD_LED_FULL_BRIGHTNESS_CV = ${modLedFullBrightnessCv} as const;
export const WEB_MOD_BAY_SPEC = ${JSON.stringify(webModBay)} as const;
export const WEB_SCOPE_MOD_INDICES = ${JSON.stringify(webModBay.map((c) => c.modIndex))} as const;
export const DESKTOP_MOD_RACK_INDICES = ${JSON.stringify(desktopModBay.map((c) => c.modIndex))} as const;
export const VST_MOD_RACK_INDICES = ${JSON.stringify(vstModBay.map((c) => c.modIndex))} as const;
export const VCV_MOD_RACK_INDICES = ${JSON.stringify(vcvModBay.map((c) => c.modIndex))} as const;

export type ModBaySpec = { modIndex: number; kind: "scope" | "led" };

export function modLedDisplayBrightness(cv01: number, active: boolean): number {
  if (!active) {
    return 0;
  }
  const clamped = Math.min(Math.max(cv01, 0), 1);
  if (clamped >= MOD_LED_FULL_BRIGHTNESS_CV) {
    return 1;
  }
  const normalized = clamped / MOD_LED_FULL_BRIGHTNESS_CV;
  return normalized * normalized;
}

export function coreKnobCountForPage(hostPage: number): number {
  return hostPage === 0 ? CORE_KNOB_COUNT : EXPANDED_CORE_KNOB_COUNT;
}

export function coreKnobLabel(hostPage: number, row: number): string {
  return HOST_PAGE_KNOB_LABELS[hostPage]?.[row] ?? "";
}

export function pairArKnobLabel(index: number): string {
  return PAIR_AR_KNOB_LABELS[index] ?? "";
}
`;
}

const paramHpp = readFileSync(join(root, "sim/ParamDisplayNames.hpp"), "utf8");
const v2ParamHpp = readFileSync(join(root, "sim/V2ParamDisplayNames.hpp"), "utf8");
const layoutHpp = readFileSync(join(root, "sim/HostPanelLayout.hpp"), "utf8");
const modLedHpp = readFileSync(join(root, "sim/ModLedBrightness.hpp"), "utf8");
const catalog = modCatalogFromHpp(layoutHpp);
const v1Table = tableFromHpp(paramHpp);
const payload = {
  pages: pagesFromHpp(paramHpp),
  table: buildV2WebTable(v1Table, v2ExpansionTailFromHpp(v2ParamHpp)),
  pairLabels: pairFromHpp(paramHpp),
  globalStrip: globalStripFromHpp(paramHpp),
  scopeSize: scopeCapacityFromHpp(layoutHpp),
  modLedFullBrightnessCv: modLedFullBrightnessFromHpp(modLedHpp),
  expandedCoreKnobCount: v2ExpandedRowCountFromHpp(v2ParamHpp),
  desktopModBay: projectModBay(catalog, "includeDesktop"),
  webModBay: projectModBay(catalog, "includeWeb"),
  vstModBay: projectModBay(catalog, "includeVst"),
  vcvModBay: projectModBay(catalog, "includeVcv"),
};
const generated = emitTs(payload);

if (checkOnly) {
  const existing = readFileSync(outPath, "utf8");
  if (existing !== generated) {
    console.error("hostDisplay.generated.ts is stale — run: node scripts/generate-host-display.mjs");
    process.exit(1);
  }
  console.log("hostDisplay.generated.ts is fresh");
} else {
  writeFileSync(outPath, generated);
  console.log(`wrote ${outPath}`);
}
